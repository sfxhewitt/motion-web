"""Render every effect on its procedural sample scene and pack the effect-browser thumbnail sprite
(icons/fx-thumbs.webp + js/fx/thumbs.js). Also writes the contact sheet to /workspace/kntc-shots/effects/.
Run with the dev server on :8765 (python3 -m http.server 8765 in the repo root)."""
import base64, json, os, sys
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = os.environ.get('BASE', 'http://localhost:8765/')
SHOTS = '/workspace/kntc-shots/effects'
JS = r"""async ({ cell, sheet }) => {
  const { sampleProject, SAMPLE_T } = await import('../js/fxsample.js');
  const { Renderer } = await import('../js/render.js');
  const { EFFECTS, CATS } = await import('../js/effects.js');
  const order = CATS.flatMap(([c]) => Object.values(EFFECTS).filter(e => e.cat === c).sort((a, b) => a.name.localeCompare(b.name)).map(e => e.id));
  const R = new Renderer(), cv = document.createElement('canvas');
  const cols = Math.ceil(Math.sqrt(order.length)), rows = Math.ceil(order.length / cols);
  const sp = document.createElement('canvas'); sp.width = cols * cell; sp.height = rows * cell; const g = sp.getContext('2d');
  // contact sheet: bigger cells with names
  const sc = 220, scols = 12, srows = Math.ceil(order.length / scols), lab = 30;
  const cs = document.createElement('canvas'); cs.width = scols * sc; cs.height = srows * (sc + lab) + 60; const k = cs.getContext('2d');
  k.fillStyle = '#191b27'; k.fillRect(0, 0, cs.width, cs.height); k.fillStyle = '#fff'; k.font = '600 30px system-ui'; k.fillText(`KINETIC effects — ${order.length} effects, rendered by the WebGL engine on procedural samples`, 16, 42);
  const errs = [];
  for (let i = 0; i < order.length; i++) {
    const id = order[i];
    for (const [size, ctx, x, y] of [[cell, g, (i % cols) * cell, Math.floor(i / cols) * cell], [sc, k, (i % scols) * sc, 60 + Math.floor(i / scols) * (sc + lab)]]) {
      const { project } = sampleProject(id, { size: 540 }); cv.width = cv.height = size; R.render(project, SAMPLE_T, cv); ctx.drawImage(cv, x, y);
    }
    const x = (i % scols) * sc, y = 60 + Math.floor(i / scols) * (sc + lab) + sc;
    k.fillStyle = '#2b2e3d'; k.fillRect(x, y, sc, lab); k.fillStyle = '#e9eaf0'; k.font = '500 15px system-ui'; k.fillText(EFFECTS[id].name, x + 6, y + 20, sc - 12);
    k.fillStyle = '#00ffa8'; k.fillRect(x, y, 3, lab);
  }
  errs.push(...R.errors, ...R.fx.errors);
  return { ids: order, cols, rows, sprite: sp.toDataURL('image/webp', 0.82), sheet: cs.toDataURL('image/png'), errs };
}"""
with sync_playwright() as p:
    b = p.chromium.launch(args=['--use-gl=swiftshader', '--enable-unsafe-swiftshader'])
    pg = b.new_page(service_workers='block'); pg.goto(BASE + 'tests/blank.html')
    r = pg.evaluate(JS, {'cell': 128, 'sheet': True})
    b.close()
def save(data_url, path):
    with open(path, 'wb') as f: f.write(base64.b64decode(data_url.split(',', 1)[1]))
save(r['sprite'], os.path.join(ROOT, 'icons', 'fx-thumbs.webp'))
os.makedirs(SHOTS, exist_ok=True); save(r['sheet'], os.path.join(SHOTS, 'contact-sheet.png'))
with open(os.path.join(ROOT, 'js', 'fx', 'thumbs.js'), 'w') as f:
    f.write('// Generated by tests/build_thumbs.py: effect thumbnail sprite layout (icons/fx-thumbs.webp).\n')
    f.write('export const THUMBS = ' + json.dumps({'src': 'icons/fx-thumbs.webp', 'cell': 128, 'cols': r['cols'], 'rows': r['rows'], 'ids': r['ids']}) + ';\n')
print(len(r['ids']), 'thumbs;', 'errors:', r['errs'][:5])
print('sprite', os.path.getsize(os.path.join(ROOT, 'icons', 'fx-thumbs.webp')), 'bytes')
